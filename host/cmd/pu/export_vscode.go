func runExportVSCode(ctx cliContext, args []string) int {
	fs := flag.NewFlagSet("pu export-vscode", flag.ContinueOnError)
	fs.SetOutput(ctx.stderr)

	familyFlag := fs.String("family", "", "Target MCU family (stm32f1|stm32f4|rp2040|rp2350|esp32|esp32s3|ch32v003)")
	outDirFlag := fs.String("out-dir", "", "Project root directory (writes .vscode/launch.json and .vscode/pico-universal-openocd.cfg)")
	serialFlag := fs.String("serial", "", "Optional Pico Universal probe hardware serial number to pin")
	pidFlag := fs.String("pid", "", "Optional approved USB PID hex to pin in generated configs (overrides PU_USB_PID)")
	elfFlag := fs.String("elf", "${workspaceFolder}/build/firmware.elf", "Path to target ELF binary for launch.json")

	if err := fs.Parse(args); err != nil {
		if errors.Is(err, flag.ErrHelp) {
			return 0
		}
		return 2
	}

	if strings.TrimSpace(*familyFlag) == "" {
		fmt.Fprintln(ctx.stderr, "pu export-vscode: --family is required")
		return 2
	}
	if strings.TrimSpace(*outDirFlag) == "" {
		fmt.Fprintln(ctx.stderr, "pu export-vscode: --out-dir is required")
		return 2
	}

	family, err := puid.NormalizeFamily(*familyFlag)
	if err != nil {
		fmt.Fprintf(ctx.stderr, "pu export-vscode: %v\n", err)
		return 2
	}

	effectivePIDRaw := strings.TrimSpace(*pidFlag)
	if effectivePIDRaw == "" {
		effectivePIDRaw = strings.TrimSpace(ctx.globalPID)
	}
	var pidHex string
	if effectivePIDRaw != "" {
		parsedPID, pErr := ParseHexUint16(effectivePIDRaw)
		if pErr != nil {
			fmt.Fprintf(ctx.stderr, "pu export-vscode: invalid --pid: %v\n", pErr)
			return 2
		}
		if parsedPID != 0 {
			pidHex = fmt.Sprintf("0x%04x", parsedPID)
		}
	} else if ctx.getenv != nil {
		if envPID := strings.TrimSpace(ctx.getenv("PU_USB_PID")); envPID != "" {
			if parsedPID, pErr := ParseHexUint16(envPID); pErr == nil && parsedPID != 0 {
				pidHex = fmt.Sprintf("0x%04x", parsedPID)
			}
		}
	}

	absOut, err := filepath.Abs(*outDirFlag)
	if err != nil {
		fmt.Fprintf(ctx.stderr, "pu export-vscode: resolve --out-dir: %v\n", err)
		return 1
	}
	vscodeDir := absOut
	if filepath.Base(absOut) != ".vscode" {
		vscodeDir = filepath.Join(absOut, ".vscode")
	}
	if err := os.MkdirAll(vscodeDir, 0o755); err != nil {
		fmt.Fprintf(ctx.stderr, "pu export-vscode: create %s: %v\n", vscodeDir, err)
		return 1
	}

	serial := strings.TrimSpace(*serialFlag)
	elfPath := strings.TrimSpace(*elfFlag)
	if elfPath == "" {
		elfPath = "${workspaceFolder}/build/firmware.elf"
	}

	ocdPath := filepath.Join(vscodeDir, "pico-universal-openocd.cfg")
	launchPath := filepath.Join(vscodeDir, "launch.json")

	ocdContent := renderVSCodeOpenOCDConfig(family, serial, pidHex)
	launchBytes, err := mergeVSCodeLaunchJSON(launchPath, buildVSCodeLaunchConfig(family, serial, pidHex, elfPath))
	if err != nil {
		fmt.Fprintf(ctx.stderr, "pu export-vscode: build launch.json: %v\n", err)
		return 1
	}

	if err := atomicWriteFile(ocdPath, []byte(ocdContent), 0o644); err != nil {
		fmt.Fprintf(ctx.stderr, "pu export-vscode: write %s: %v\n", ocdPath, err)
		return 1
	}
	if err := atomicWriteFile(launchPath, launchBytes, 0o644); err != nil {
		fmt.Fprintf(ctx.stderr, "pu export-vscode: write %s: %v\n", launchPath, err)
		return 1
	}

	fmt.Fprintf(ctx.stdout, "Exported VS Code debug configuration for %s:\n  %s\n  %s\n", family, launchPath, ocdPath)
	return 0
}

func renderVSCodeOpenOCDConfig(family, serial, pidHex string) string {
	serialLine := "# adapter serial <PICO_UNIVERSAL_SERIAL>"
	if serial != "" {
		serialLine = "adapter serial " + serial
	}
	vidPidLine := ""
	if pidHex != "" {
		vidPidLine = "cmsis_dap_vid_pid 0x2e8a " + pidHex
	}

	switch family {
	case "esp32":
		base := string(catalog.EmbeddedESP32OpenOCDConfig())
		lines := []string{
			"# Generated by `pu export-vscode --family esp32`",
			serialLine,
		}
		if vidPidLine != "" {
			lines = append(lines, vidPidLine)
		}
		return strings.Join(lines, "\n") + "\n" + base

	case "esp32s3":
		lines := []string{
			"# Generated by `pu export-vscode --family esp32s3`",
			"source [find interface/cmsis-dap.cfg]",
			serialLine,
		}
		if vidPidLine != "" {
			lines = append(lines, vidPidLine)
		}
		lines = append(lines,
			"transport select jtag",
			"adapter speed 5000",
			"source [find target/esp32s3.cfg]",
			"",
		)
		return strings.Join(lines, "\n")

	case "ch32v003":
		extra := ""
		if serial != "" {
			extra += " --serial " + serial
		}
		if pidHex != "" {
			extra += " --pid " + pidHex
		}
		return strings.Join([]string{
			"# Generated by `pu export-vscode --family ch32v003`",
			"# Note: WCH CH32V003 uses Pico Universal's composite 1-wire SWIO GDB RSP engine",
			"# via stdio pipe in launch.json (`| pu gdb-pipe ...`). Optional manual TCP relay:",
			"#   pu gdb-pipe --listen 127.0.0.1:3333" + extra,
			"",
		}, "\n")

	default:
		targetCfg := map[string]string{
			"stm32f1": "target/stm32f1x.cfg",
			"stm32f4": "target/stm32f4x.cfg",
			"rp2040":  "target/rp2040.cfg",
			"rp2350":  "target/rp2350.cfg",
		}[family]
		lines := []string{
			"# Generated by `pu export-vscode --family " + family + "`",
			"source [find interface/cmsis-dap.cfg]",
			serialLine,
		}
		if vidPidLine != "" {
			lines = append(lines, vidPidLine)
		}
		lines = append(lines,
			"transport select swd",
			"adapter speed 1000",
			"source [find "+targetCfg+"]",
			"",
		)
		return strings.Join(lines, "\n")
	}
}

func buildVSCodeLaunchConfig(family, serial, pidHex, elfPath string) map[string]any {
	if family == "ch32v003" {
		puExe, err := resolveSafeExecutablePath()
		if err != nil {
			puExe = "pu"
		}
		extraArgs := ""
		if serial != "" {
			extraArgs += " --serial " + serial
		}
		if pidHex != "" {
			extraArgs += " --pid " + pidHex
		}
		return map[string]any{
			"name":               "Pico Universal Debug (ch32v003 SWIO)",
			"type":               "cortex-debug",
			"request":            "launch",
			"servertype":         "external",
			"cwd":                "${workspaceFolder}",
			"executable":         elfPath,
			"gdbPath":            "riscv-none-elf-gdb",
			"gdbTarget":          fmt.Sprintf(`| "%s" gdb-pipe --family ch32v003%s`, puExe, extraArgs),
			"runToEntryPoint":    "main",
			"postLaunchCommands": []string{"set breakpoint auto-hw off"},
		}
	}

	interfaceMode := "swd"
	gdbBin := "arm-none-eabi-gdb"
	if family == "esp32" || family == "esp32s3" {
		interfaceMode = "jtag"
		gdbBin = "xtensa-esp32-elf-gdb"
		if family == "esp32s3" {
			gdbBin = "xtensa-esp32s3-elf-gdb"
		}
	}
	cfg := map[string]any{
		"name":            "Pico Universal Debug (" + family + ")",
		"type":            "cortex-debug",
		"request":         "launch",
		"servertype":      "openocd",
		"interface":       interfaceMode,
		"cwd":             "${workspaceFolder}",
		"executable":      elfPath,
		"gdbPath":         gdbBin,
		"runToEntryPoint": "main",
		"configFiles": []string{
			"${workspaceFolder}/.vscode/pico-universal-openocd.cfg",
		},
	}
	if family == "esp32" || family == "esp32s3" {
		cfg["preLaunchCommands"] = []string{"set remotetimeout 20"}
	}
	return cfg
}

func mergeVSCodeLaunchJSON(launchPath string, newCfg map[string]any) ([]byte, error) {
	doc := map[string]any{
		"version": "0.2.0",
	}

	var existingConfigs []any
	if raw, err := os.ReadFile(launchPath); err == nil {
		if len(strings.TrimSpace(string(raw))) > 0 {
			var existingDoc map[string]any
			if jErr := json.Unmarshal(raw, &existingDoc); jErr != nil {
				return nil, fmt.Errorf("existing %s is not valid JSON (refusing to overwrite): %w", launchPath, jErr)
			}
			for k, v := range existingDoc {
				doc[k] = v
			}
			if _, ok := doc["version"]; !ok {
				doc["version"] = "0.2.0"
			}
			if cfgs, ok := existingDoc["configurations"].([]any); ok {
				existingConfigs = cfgs
			}
		}
	} else if !errors.Is(err, os.ErrNotExist) {
		return nil, err
	}

	newName, _ := newCfg["name"].(string)
	replaced := false
	merged := make([]any, 0, len(existingConfigs)+1)
	for _, entry := range existingConfigs {
		if m, ok := entry.(map[string]any); ok {
			if name, _ := m["name"].(string); name == newName && newName != "" {
				merged = append(merged, newCfg)
				replaced = true
				continue
			}
		}
		merged = append(merged, entry)
	}
	if !replaced {
		merged = append(merged, newCfg)
	}
	doc["configurations"] = merged

	encoded, err := json.MarshalIndent(doc, "", "  ")
	if err != nil {
		return nil, err
	}
	return append(encoded, '\n'), nil
}
