#!/usr/bin/env python3
"""Generate config/flash_layout.h from config/flash_layout.json."""

import argparse
import json
import re
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
DEFAULT_IN = ROOT / "config" / "flash_layout.json"
DEFAULT_OUT = ROOT / "config" / "flash_layout.h"


def _is_strict_int(value: object) -> bool:
    return type(value) is int


def load_and_validate_layout(path: Path) -> dict:
    raw = json.loads(path.read_text(encoding="utf-8"))
    if not isinstance(raw, dict):
        raise ValueError("flash layout root must be a JSON object")

    for field in ("flash_base", "flash_size", "page_size", "sector_size"):
        if field not in raw or not _is_strict_int(raw[field]):
            raise ValueError(f"{field} must be an integer")

    flash_base = raw["flash_base"]
    flash_size = raw["flash_size"]
    page_size = raw["page_size"]
    sector_size = raw["sector_size"]

    if flash_base < 0 or flash_size <= 0 or page_size <= 0 or sector_size <= 0:
        raise ValueError("flash geometry values must be positive")
    if sector_size % page_size != 0:
        raise ValueError("sector_size must be a multiple of page_size")
    if flash_size % sector_size != 0:
        raise ValueError("flash_size must be a multiple of sector_size")

    partitions = raw.get("partitions")
    if not isinstance(partitions, list) or not partitions:
        raise ValueError("partitions must be a non-empty list")

    seen_names: set[str] = set()
    seen_macros: set[str] = set()
    cursor = 0

    for part in partitions:
        if not isinstance(part, dict):
            raise ValueError("each partition entry must be an object")
        name = part.get("name")
        macro = part.get("macro")
        offset = part.get("offset")
        size = part.get("size")
        executable = part.get("executable")

        if not isinstance(name, str) or not name:
            raise ValueError("partition name must be a non-empty string")
        if not isinstance(macro, str) or not re.fullmatch(r"SLOT_[A-Z0-9_]+", macro):
            raise ValueError(f"invalid partition macro {macro!r}; expected SLOT_[A-Z0-9_]+")
        if not _is_strict_int(offset) or not _is_strict_int(size):
            raise ValueError(f"partition {name!r} offset and size must be integers")
        if type(executable) is not bool:
            raise ValueError(f"partition {name!r} executable flag must be a boolean")
        if name in seen_names:
            raise ValueError(f"duplicate partition name: {name!r}")
        if macro in seen_macros:
            raise ValueError(f"duplicate partition macro: {macro!r}")
        if offset < 0 or size <= 0:
            raise ValueError(f"partition {name!r} must have non-negative offset and positive size")
        if offset % sector_size != 0:
            raise ValueError(f"partition {name!r} offset 0x{offset:X} is not {sector_size}-byte sector aligned")
        if size % sector_size != 0:
            raise ValueError(f"partition {name!r} size 0x{size:X} is not {sector_size}-byte sector aligned")
        if offset < cursor:
            raise ValueError(
                f"partition {name!r} at 0x{offset:X} overlaps or precedes previous end 0x{cursor:X}"
            )
        end = offset + size
        if end > flash_size:
            raise ValueError(
                f"partition {name!r} end 0x{end:X} exceeds flash_size 0x{flash_size:X}"
            )

        seen_names.add(name)
        seen_macros.add(macro)
        cursor = end

    return raw


def render_header(layout: dict) -> str:
    lines = [
        "/* Generated by tools/gen_flash_layout.py from config/flash_layout.json; do not edit. */",
        "#ifndef FLASH_LAYOUT_H",
        "#define FLASH_LAYOUT_H",
        "",
        f"#define FLASH_BASE_ADDR (0x{layout['flash_base']:08X}U)",
        f"#define FLASH_TOTAL_SIZE (0x{layout['flash_size']:08X}U)",
        f"#define FLASH_PAGE_SIZE (0x{layout['page_size']:08X}U)",
        f"#define FLASH_SECTOR_SIZE (0x{layout['sector_size']:08X}U)",
        "",
    ]
    for part in layout["partitions"]:
        macro = part["macro"]
        lines.extend(
            [
                f"#define {macro}_OFFSET (0x{part['offset']:08X}U)",
                f"#define {macro}_ADDR (FLASH_BASE_ADDR + {macro}_OFFSET)",
                f"#define {macro}_SIZE (0x{part['size']:08X}U)",
                "",
            ]
        )
    lines.append("#endif /* FLASH_LAYOUT_H */")
    return "\n".join(lines) + "\n"


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument(
        "--in",
        dest="input_path",
        type=Path,
        default=DEFAULT_IN,
        help="Path to input flash_layout.json",
    )
    parser.add_argument(
        "--out",
        dest="output_path",
        type=Path,
        default=DEFAULT_OUT,
        help="Path to generated flash_layout.h",
    )
    parser.add_argument(
        "--check",
        action="store_true",
        help="Verify that --out matches the generated header without writing",
    )
    args = parser.parse_args(argv)

    try:
        layout = load_and_validate_layout(args.input_path)
    except (OSError, json.JSONDecodeError, ValueError) as exc:
        print(f"gen_flash_layout.py: {exc}", file=sys.stderr)
        return 1

    rendered = render_header(layout)

    if args.check:
        if not args.output_path.is_file():
            print(f"gen_flash_layout.py: missing {args.output_path}", file=sys.stderr)
            return 1
        actual = args.output_path.read_text(encoding="utf-8")
        if actual != rendered:
            print(
                f"gen_flash_layout.py: {args.output_path} is out of date; regenerate from {args.input_path}",
                file=sys.stderr,
            )
            return 1
        return 0

    args.output_path.parent.mkdir(parents=True, exist_ok=True)
    with args.output_path.open("w", encoding="utf-8", newline="\n") as fh:
        fh.write(rendered)
    return 0


if __name__ == "__main__":
    sys.exit(main())
